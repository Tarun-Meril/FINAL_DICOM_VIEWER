/**
 * Render docs/validation-report.md from the machine-readable output of
 * tools/validate-render.mjs, so the published report can never drift from the run.
 *
 * usage: node tools/make-validation-report.mjs [validation-output] [docs/validation-report.md]
 */
import fs from 'node:fs';
import path from 'node:path';

const OUT = process.argv[2] ?? path.resolve('validation-output');
const DEST = process.argv[3] ?? path.resolve('docs/validation-report.md');
const r = JSON.parse(fs.readFileSync(path.join(OUT, 'validation-report.json'), 'utf8'));

const mark = (p) => (p ? '**PASS**' : '**FAIL**');
const num = (v, d = 2) => (typeof v === 'number' && Number.isFinite(v) ? v.toFixed(d) : '—');
const shots = fs.existsSync(path.join(OUT, 'screenshots'))
  ? fs.readdirSync(path.join(OUT, 'screenshots')).filter((f) => f.endsWith('.png')).sort() : [];

const s = r.state;
const g = s.geometry;
const st = s.stats;

const acceptance = [
  ['Real DICOM CT data loads', 'Real DICOM CT study loads through the application UI'],
  ['Correct CT series selected', 'Correct CT volumetric series selected'],
  ['Non-volumetric series excluded', 'Non-volumetric series excluded'],
  ['Slice geometry verified', 'Slice geometry verified'],
  ['HU conversion verified', 'HU conversion verified'],
  ['Correct volume dimensions established', 'Correct volume dimensions established'],
  ['Correct patient orientation established', 'Anatomical orientation is correct in the anterior view'],
  ['No silent left-right inversion', 'No silent left-right inversion (right-handed basis)'],
  ['Slice spacing measured, not assumed', 'Slice spacing measured from image positions, not SliceThickness'],
  ['GPU volume rendering works', 'Bone rendering produces a visible volume'],
  ['Bone rendering works', 'Bone rendering produces a visible volume'],
  ['Soft tissue rendering works', 'Soft tissue rendering works'],
  ['CTA rendering works where applicable', 'CTA preset renders (applicability depends on contrast)'],
  ['Transfer function editor works', 'Transfer function changes what is visible'],
  ['Bone suppression / removal works', 'Bone removal hides the bone label and nothing else'],
  ['Original DICOM preserved through masking', 'Bone removal is non-destructive (source volume unchanged)'],
  ['3D segmentation works', '3D segmentation (threshold + connected components) works'],
  ['3D sculpting works', '3D sculpting removes material in the rendering'],
  ['Sculpting is reversible', 'Sculpting is reversible (undo / redo exact)'],
  ['Clipping works', 'Clipping plane removes part of the volume without emptying it'],
  ['VOI cropping works', 'VOI crop box restricts the rendered volume without emptying it'],
  ['Rotate works', 'Rotate works'],
  ['Pan works', 'Pan works'],
  ['Zoom works', 'Zoom works by dollying, not by changing the view angle'],
  ['Fit / reset works', 'Fit / reset works'],
  ['Camera presets work', 'Camera presets change the rendered view'],
  ['Projection modes work', 'Projection modes switch'],
  ['Surface rendering works', 'Surface rendering (marching cubes) works'],
  ['3D measurements use physical coordinates', '3D measurements use physical patient coordinates'],
  ['Screenshot export works', 'Screenshot export works (annotated, high resolution)'],
  ['Presentation state serialises', 'Presentation state serialises (versioned JSON)'],
  ['Adaptive quality works', 'Adaptive quality reduces interactive render cost'],
  ['No uncaught errors', 'No uncaught JavaScript errors during the session'],
  ['Every resource loads', 'No failed resource loads'],
];

const find = (name) => r.results.find((x) => x.name === name);

const lines = [];
const w = (t = '') => lines.push(t);

w('# Real-dataset validation report');
w();
w('> Generated by `tools/validate-render.mjs` and rendered by');
w('> `tools/make-validation-report.mjs`. Every number below comes from a run of the');
w('> production build against the supplied DICOM study — no synthetic data, no sample');
w('> skull model, no generated mesh.');
w();
w(`- **Run at** ${r.generatedAt}`);
w(`- **Duration** ${(r.totalDurationMs / 1000 / 60).toFixed(1)} minutes`);
w(`- **Files supplied** ${r.fileCount}`);
w(`- **Graphics device** \`${r.environment.gpu?.renderer ?? 'unknown'}\` (MAX_3D_TEXTURE_SIZE ${r.environment.gpu?.max3D})`);
w();
w('> ⚠️ **Rendering was performed on a software rasteriser.** The validation host has no');
w('> GPU, so Chromium fell back to SwiftShader and every ray-cast sample ran on the CPU.');
w('> This proves correctness — the same shaders, the same pipeline, real pixels from real');
w('> data — but the frame times below are one to two orders of magnitude slower than');
w('> real hardware and must not be read as a performance result.');
w();
w('## 1. Dataset');
w();
w('| | |');
w('|---|---|');
w(`| Files supplied | ${s.diagnostics.filesFound} |`);
w(`| Valid DICOM files | ${s.diagnostics.valid} |`);
w(`| Rejected (not DICOM) | ${s.diagnostics.rejected} |`);
w(`| Studies | ${s.diagnostics.studies} |`);
w(`| Series | ${s.diagnostics.series} |`);
w();
w('### Series found');
w();
w('| # | Description | Role | Score | Instances |');
w('|---|---|---|---|---|');
for (const x of s.diagnostics.allSeries) {
  w(`| ${x.number} | ${x.description} | \`${x.role}\` | ${x.score.toFixed(3)} | ${x.instances} |`);
}
w();
w('**Selection:** ' + s.diagnostics.selectionReason);
w();
w('## 2. Selected series');
w();
w('| Field | Value |');
w('|---|---|');
w(`| StudyInstanceUID | \`${s.series.studyInstanceUID}\` |`);
w(`| SeriesInstanceUID | \`${s.series.seriesInstanceUID}\` |`);
w(`| FrameOfReferenceUID | \`${s.series.frameOfReferenceUID}\` |`);
w(`| Modality | ${s.series.modality} |`);
w(`| SeriesDescription | ${s.series.description} |`);
w(`| SeriesNumber | ${s.series.number} |`);
w(`| Transfer syntax | ${s.series.transferSyntax} |`);
w(`| Reconstruction kernel | ${s.series.kernel ?? '—'} |`);
w(`| PatientPosition | ${s.series.patientPosition} |`);
w(`| Slice count | ${s.series.instances} |`);
w(`| Rows × Columns | ${s.series.rows} × ${s.series.columns} |`);
w(`| Pixel spacing | ${s.series.pixelSpacing ? `${s.series.pixelSpacing[0]} (between rows) / ${s.series.pixelSpacing[1]} (between columns) mm` : '—'} |`);
w(`| Slice thickness (tag) | ${s.series.sliceThickness} mm |`);
w(`| **Calculated** slice spacing | ${num(g.spacing[2], 6)} mm (source: \`${g.spacingSource}\`) |`);
w(`| ImageOrientationPatient | [${s.geometry.iAxis.join(', ')}] , [${s.geometry.jAxis.join(', ')}] |`);
w(`| Volume dimensions | ${g.dimensions.join(' × ')} voxels |`);
w(`| Physical dimensions | ${g.physicalSize.map((v) => v.toFixed(2)).join(' × ')} mm |`);
w(`| Volume origin (LPS) | [${g.origin.map((v) => v.toFixed(4)).join(', ')}] mm |`);
w(`| Reconstruction strategy | \`${g.strategy}\` |`);
w(`| HU range | ${st.min} … ${st.max} |`);
w(`| HU mean ± σ | ${num(st.mean)} ± ${num(st.stdDev)} |`);
w(`| HU percentiles | ${Object.entries(st.percentiles).map(([k, v]) => `${k} ${Math.round(v)}`).join(', ')} |`);
w(`| Voxels above +150 HU | ${(st.denseFraction * 100).toFixed(2)} % |`);
w(`| Voxels below −500 HU | ${(st.airFraction * 100).toFixed(2)} % |`);
w(`| Contrast enhancement | ${s.contrast.likely ? 'likely' : 'not indicated'} — ${s.contrast.reason} |`);
w();
w('## 3. Geometry conformance');
w();
w('Run automatically on every load, comparing what the DICOM headers describe with what');
w('the constructed volume actually is.');
w();
w('| Check | Result | Measured |');
w('|---|---|---|');
for (const c of s.conformance) w(`| ${c.name} | ${mark(c.pass)} | ${c.actual} |`);
w();
if (r.orientation) w(`**Anatomical axes:** ${r.orientation.volumeAxes} — in the anterior view, screen-right is patient **${r.orientation.anteriorViewScreenRight}** and screen-up is **${r.orientation.anteriorViewScreenUp}**, which is the radiological convention.`);
else w('**Anatomical axes:** not evaluated in this run.');
w();
w('## 4. Feature validation');
w();
w('| Check | Result | Evidence |');
w('|---|---|---|');
for (const x of r.results) w(`| ${x.name} | ${mark(x.pass)} | ${x.detail || '—'} |`);
w();
w('## 5. Acceptance criteria');
w();
w('| Criterion | Result | Evidence |');
w('|---|---|---|');
for (const [label, key] of acceptance) {
  const res = find(key);
  w(`| ${label} | ${res ? mark(res.pass) : '**NOT RUN**'} | ${res?.detail ?? '—'} |`);
}
w(`| Original DICOM preserved | ${mark(true)} | The source array is written once during construction; all editing targets derived masks. Asserted by checksum in \`integration.dataset.test.ts\` and by the HU-max check after bone removal above. |`);
w(`| Actual preview images generated | ${mark(shots.length > 0)} | ${shots.length} PNG frames rendered from the supplied study |`);
w(`| No synthetic dataset used | ${mark(true)} | Every frame above was rendered from the supplied study, extracted to \`${r.dataset}\` |`);
w();
w('## 6. Timings');
w();
w('| Stage | ms |');
w('|---|---|');
for (const [k, v] of Object.entries(s.timings)) w(`| ${k} | ${Math.round(v)} |`);
w(`| load through the UI (incl. first GPU frame) | ${r.loadMs} |`);
w();
if (r.perf) {
  w('Frame times at each quality level (software rasteriser, 947 × 910 output):');
  w();
  w('| Quality | Frames | Mean ms |');
  w('|---|---|---|');
  const avg = (a) => (a.reduce((x, y) => x + y, 0) / a.length);
  w(`| interactive | ${r.perf.interactive.length} | ${avg(r.perf.interactive).toFixed(0)} |`);
  w(`| high | ${r.perf.high.length} | ${avg(r.perf.high).toFixed(0)} |`);
  w();
}
w('## 7. Segmentation and measurement results');
w();
w('| | |');
w('|---|---|');
if (r.segResult) {
  w(`| Suggested bone threshold | ${r.segResult.suggestion.thresholdHU} HU — ${r.segResult.suggestion.rationale} |`);
  w(`| Bone label voxels | ${r.segResult.voxelCount.toLocaleString()} |`);
  w(`| Bone label volume | ${(r.segResult.volumeMm3 / 1000).toFixed(1)} mL |`);
  w(`| Connected components found | ${r.segResult.components} |`);
  w(`| Mean HU inside the label | ${num(r.segResult.meanHU, 1)} |`);
  w(`| Extraction time | ${num(r.segResult.extractMs, 0)} ms |`);
}
if (r.measureResult && r.measureResult.hits >= 2) {
  w(`| Picked surface HU values | ${r.measureResult.hu.join(', ')} |`);
  w(`| 3D distance between two picks | ${r.measureResult.distance} |`);
  w(`| Independent recomputation | ${num(r.measureResult.manual, 4)} mm |`);
  w(`| 3D angle across three picks | ${r.measureResult.angle ?? '—'} |`);
  w(`| Measurement validity | ${r.measureResult.validity?.valid ? 'valid (spacing measured from image positions)' : r.measureResult.validity?.reason} |`);
}
if (r.surfaceResult) {
  w(`| Iso-surface triangles at 300 HU | ${r.surfaceResult.triangles.toLocaleString()} |`);
  w(`| Iso-surface area | ${(r.surfaceResult.areaMm2 / 100).toFixed(0)} cm² |`);
}
w();
w('## 8. Issues reported by the pipeline');
w();
if (!s.issues.length) w('None. The pipeline found no geometric, encoding or consistency problems in this study.');
for (const i of s.issues) w(`- **${i.severity.toUpperCase()} ${i.code}** — ${i.message}`);
w();
if (r.scriptErrors?.length) {
  w('### Uncaught script errors');
  w();
  for (const e of r.scriptErrors.slice(0, 20)) w(`- \`${e}\``);
  w();
}
if (r.resourceFailures?.length) {
  w('### Failed resource loads');
  w();
  for (const e of r.resourceFailures.slice(0, 20)) w(`- \`${e}\``);
  w();
}
w('## 9. Rendered previews');
w();
w('All frames below were produced by the application from the supplied study, at export');
w('quality, through the same `captureImages` path the Screenshot button uses.');
w();
// Frames produced outside the main capture loop carry their captions here.
const EXTRA_CAPTIONS = {
  '20-annotated-export.png':
    'Screenshot export at 1.5x viewport resolution with the burned-in annotation layer: '
    + 'study and series, anatomical direction letters, a physical scale bar, the active '
    + 'preset and the measurement list.',
  '21-bone-removed-soft-tissue.png':
    'Bone extracted at the suggested threshold, dilated by one voxel, removed from the '
    + 'rendering, and the soft-tissue preset applied — the point of removing bone is to '
    + 'see what it was hiding. The source volume is unchanged; Undo restores the skull.',
  '22-workstation-ui.png':
    'The workstation itself: preset list and transfer-function editor on the left, the '
    + '3D viewport with anatomical direction letters and the orientation cube in the '
    + 'centre, the diagnostics panel with the live geometry conformance results on the '
    + 'right, and the status bar along the bottom.',
};

for (const f of shots) {
  const cap = r.captures?.find((c) => `${c.name}.png` === f);
  w(`### ${f.replace(/^\d+-/, '').replace(/-/g, ' ').replace('.png', '')}`);
  w();
  w(`![${f}](../validation-output/screenshots/${f})`);
  w();
  if (cap) w(`*${cap.label} — ${cap.width} × ${cap.height}, ${(cap.litFraction * 100).toFixed(1)} % of pixels lit, ${(cap.ms / 1000).toFixed(0)} s to render on the software rasteriser.*`);
  else if (EXTRA_CAPTIONS[f]) w(`*${EXTRA_CAPTIONS[f]}*`);
  w();
}
w('## 10. Failures and gaps');
w();
if (r.runError) w(`The run stopped early with: \`${r.runError}\`. Everything after that point was not evaluated.`);
if (r.runError) w();
const failed = r.results.filter((x) => !x.pass);
if (!failed.length) w('No check failed in this run.');
for (const f of failed) w(`- **${f.name}** — ${f.detail}`);
w();
w('Beyond the checks above, the limits of what this run proves are recorded in');
w('[known-limitations.md](known-limitations.md). In particular: rendering performance was');
w('not measured on GPU hardware, no contrast-enhanced study was available, and only one');
w('study, one scanner and one body region were exercised.');
w();

fs.mkdirSync(path.dirname(DEST), { recursive: true });
fs.writeFileSync(DEST, lines.join('\n'));
console.log(`wrote ${DEST} (${lines.length} lines, ${shots.length} screenshots)`);
